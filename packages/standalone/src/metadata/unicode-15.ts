/**
 * CPython 3.12's `\w` for `str` patterns: `Py_UNICODE_ISALNUM(ch) || ch == '_'`.
 *
 * Not the host runtime's `\w` (ASCII-only without `u`) and not UTS #18's word property.
 * CPython's set is `\p{L} | \p{N} | _`, so it *excludes* combining marks and ZWJ/ZWNJ that
 * UTS #18 includes and *includes* `Nl`/`No` that `\p{Nd}` omits. Spelling it as
 * `[\p{Alphabetic}\p{M}\p{Nd}\p{Pc}\u200c\u200d]` disagreed with the pin on 8561 code
 * points — 7646 of them marks admitted as word characters and 915 numerics rejected — on every
 * runtime, independently of the host ICU version.
 */
export function isPythonWord(codePoint: number): boolean {
  return containsCodePoint(PYTHON_312_WORD_RANGES, codePoint);
}

/**
 * The pinned tables as regex character-class bodies, for interpolation into
 * `[...]` or `[^...]` under the `u` flag.
 *
 * A `\p{L}`/`\p{N}`/`\p{Nd}` escape resolves against the *host's* Unicode data,
 * which moves independently of the pin — Node 22 ships Unicode 16 and assigns
 * code points Unicode 15 leaves unassigned. These resolve against the committed
 * tables instead, which is what the parity contract requires.
 *
 * Never interpolate either of these into a pattern carrying the `i` flag.
 * JavaScript expands a character class with the host's case-fold table, so `iu`
 * re-admits code points the pin excludes — measured as exactly U+0345, U+A7CB
 * and U+A7DC for the word class, and zero under a plain `u`. That is the defect
 * `dfd3dc680` reverted, and it would make a "no `\p{...}` escapes" guard certify
 * an invariant that does not hold.
 */
export const PYTHON_312_WORD_CLASS: string = rangesToClassBody(PYTHON_312_WORD_RANGES);

/** The `str.isdecimal()` table as a class body. Same `i`-flag caveat as above. */
export const PYTHON_312_DECIMAL_CLASS: string = rangesToClassBody(PYTHON_312_DECIMAL_RANGES);

/** Fresh first-party lower-bound lookup over independently reproduced Unicode data. */
export function containsCodePoint(
  ranges: ReadonlyArray<readonly [number, number]>,
  point: number,
): boolean {
  let first = 0;
  let after = ranges.length;
  while (first < after) {
    const probe = first + Math.floor((after - first) / 2);
    const interval = ranges[probe];
    if (interval === undefined) return false;
    if (interval[1] < point) first = probe + 1;
    else after = probe;
  }
  const interval = ranges[first];
  return interval !== undefined && interval[0] <= point && point <= interval[1];
}

function rangesToClassBody(ranges: ReadonlyArray<readonly [number, number]>): string {
  const codePointEscape = (point: number): string => `\\u{${point.toString(16)}}`;
  return ranges
    .map(([start, end]) =>
      start === end ? codePointEscape(start) : `${codePointEscape(start)}-${codePointEscape(end)}`,
    )
    .join('');
}
