export const PYTHON_312_CASE_DATA_SHA256 =
  '09cfb36df4811cc07fdbe9e177b06fce849e5ab1bba38dd0746a4a8eb44b8c23';

// Runtime helpers are freshly implemented; the verified Unicode data above is retained.
const TITLE_MAPPINGS = new Map(PYTHON_312_TITLE_MAPPINGS);
const LOWER_MAPPINGS = new Map(PYTHON_312_LOWER_MAPPINGS);

/** The pinned title-case mapping, with a new word starting after any uncased character. */
export function pythonTitle(text: string): string {
  const characters = [...text];
  const followedByCased = new Uint8Array(characters.length);
  let followingCased = false;
  for (let index = characters.length - 1; index >= 0; index -= 1) {
    followedByCased[index] = Number(followingCased);
    const point = characters[index]?.codePointAt(0) ?? 0;
    if (!containsCodePoint(PYTHON_312_CASE_IGNORABLE_RANGES, point)) {
      followingCased = containsCodePoint(PYTHON_312_CASED_RANGES, point);
    }
  }
  const letters: string[] = [];
  let initial = true;
  let precedingCased = false;
  for (let index = 0; index < characters.length; index += 1) {
    const letter = characters[index] ?? '';
    const point = letter.codePointAt(0) ?? 0;
    const mapped = initial
      ? (TITLE_MAPPINGS.get(point) ?? letter)
      : point === 0x03a3 && precedingCased && !followedByCased[index]
        ? '\u03c2'
        : (LOWER_MAPPINGS.get(point) ?? letter);
    letters.push(mapped);
    initial = !containsCodePoint(PYTHON_312_CASED_RANGES, point);
    if (!containsCodePoint(PYTHON_312_CASE_IGNORABLE_RANGES, point)) {
      precedingCased = !initial;
    }
  }
  return letters.join('');
}

export function pythonFirstCharIsUpper(text: string): boolean {
  const point = text.codePointAt(0);
  return point !== undefined && containsCodePoint(PYTHON_312_UPPERCASE_RANGES, point);
}
